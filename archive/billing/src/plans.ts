// ── Helpers ─────────────────────────────────────────────────

export function getPlanConfig(plan: PlanName): PlanConfig {
	return PLAN_CONFIG[plan];
}

export function getPlanOrder(plan: PlanName): number {
	return PLAN_CONFIG[plan].order;
}

export function isWithinLimit(used: number, limit: number | null): boolean {
	return limit === null || used < limit;
}

export function findMinimumPlanFor(feature: keyof PlanFeatures): PlanName {
	for (const plan of PLAN_NAMES) {
		if (PLAN_CONFIG[plan].features[feature]) {
			return plan;
		}
	}
	return "enterprise";
}

export function findMinimumPlanForLimit(
	limitKey: keyof PlanLimits,
	needed: number,
): PlanName | null {
	for (const plan of PLAN_NAMES) {
		const limit = PLAN_CONFIG[plan].limits[limitKey];
		if (limit === null || (typeof limit === "number" && limit >= needed)) {
			return plan;
		}
	}
	return null;
}

